# Data-region geometry derived from the table above:
#   name -> (total cw, ecc cw, mapping rows, mapping cols,
#            data cw, num blocks)
_DM_GEOM: dict[str, tuple[int, int, int, int, int, int]] = {}
for _n, (_tot, _ecc, _br, _bc, _nr, _nc) in _DM_SIZES.items():
    _mr, _mc = _br * _nr, _bc * _nc
    _blocks = _nr * _nc
    assert _mr * _mc >= _tot * 8, f"{_n}: mapping too small for {_tot} cw"
    _DM_GEOM[_n] = (_tot, _ecc, _mr, _mc, _tot - _ecc, _blocks)

_DM_ORDER = sorted(_DM_GEOM, key=lambda n: _DM_GEOM[n][0])


def _dm_ascii_codewords(text: str) -> list[int]:
    """ASCII encodation (high-level): plain values 1..128, digit pairs
    compressed to 2..104; never emits codes 201..231, so no latch shifts."""
    raw = text.encode("utf-8")
    words: list[int] = []
    i = 0
    while i < len(raw):
        ch = raw[i]
        nxt = raw[i + 1] if i + 1 < len(raw) else None
        if (ch is not None and nxt is not None
                and 48 <= ch <= 57 and 48 <= nxt <= 57):
            words.append((nxt - 48) + 10 * (ch - 48) + 130)
            i += 2
        else:
            words.append(ch + 1)
            i += 1
    return words


def _dm_random_bit(row: int, col: int, height: int, width: int) -> bool:
    """Pseudo-random module pattern for unused padding positions
    (ISO/IEC 16022 Annex X)."""
    r, c = row + 1, col + 1
    tmp = ((r * c) % 7) + 2 * r * c + height * width
    if (tmp % 3) == 0:
        return False
    return ((tmp - 1) % 3) == 0


def _dm_module_positions(rows: int, cols: int) -> list[tuple[int, int]]:
    """Mapping-matrix traversal order (ISO/IEC 16022 Annex D).

    Returns one (row, col) per module-bit in codeword order, MSB first —
    exactly ``rows*cols`` positions, each used once.  Implements the
    classic diagonal "streak" walk plus the four corner cases that wrap
    around symbol edges.  All coordinates are taken modulo the mapping
    matrix, matching the reference implementation ("utah" placement).
    """
    grid = [[False] * cols for _ in range(rows)]
    order: list[tuple[int, int]] = []

    def row_sub(i):
        return (i + rows) % rows

    def col_sub(j):
        return (j + cols) % cols

    def put(r, c):
        if not grid[r][c]:
            grid[r][c] = True
            order.append((r, c))

    def corner1():
        # (r-1+R, c-1), (r-1+R, c), (R, c), (R, c+1), (R, c+2),
        # (r, c+2-C), (r+1, c+2-C), (r+2, c+2-C)   with r=R-1, c=0
        put(row_sub(rows - 2), col_sub(cols - 1))
        put(row_sub(rows - 2), 0)
        put(row_sub(rows - 1), 0)
        put(0, 1)
        put(0, 2)
        put(1, cols - 2)
        put(2, cols - 2)
        put(3, cols - 2)

    def corner2():
        # r=0, c=C-4
        put(row_sub(rows - 1), 0)
        put(row_sub(rows - 1), col_sub(cols - 1))
        put(0, col_sub(cols - 3))
        put(0, col_sub(cols - 2))
        put(0, col_sub(cols - 1))
        put(1, col_sub(cols - 3))
        put(1, col_sub(cols - 2))
        put(1, col_sub(cols - 1))

    def corner3():
        # r=R-1, c=2, R%8==0, C==8
        put(row_sub(rows - 1), 0)
        put(row_sub(rows - 1), col_sub(cols - 1))
        put(0, col_sub(cols - 3))
        put(0, col_sub(cols - 2))
        put(0, col_sub(cols - 1))
        put(1, col_sub(cols - 3))
        put(1, col_sub(cols - 2))
        put(1, col_sub(cols - 1))

    def corner4():
        # r=R-3, c=0, R%8==0, C==8
        put(row_sub(rows - 3), 0)
        put(row_sub(rows - 2), 0)
        put(row_sub(rows - 1), 0)
        put(row_sub(rows - 1), 1)
        put(row_sub(rows - 1), 2)
        put(0, col_sub(cols - 4))
        put(0, col_sub(cols - 3))
        put(0, col_sub(cols - 2))

    def utah(r, c):
        """Standard 'utah' stamp of 8 bits anchored at (r, c)."""
        put(row_sub(r - 1), col_sub(c + 1))
        put(row_sub(r - 1), col_sub(c + 2))
        put(row_sub(r), col_sub(c + 2))
        put(row_sub(r + 1), col_sub(c + 2))
        put(row_sub(r + 2), col_sub(c + 1))
        put(row_sub(r + 2), col_sub(c))
        put(row_sub(r + 3), col_sub(c))
        put(row_sub(r + 4), col_sub(c))

    def place(r, c):
        if r == rows - 1 and c == 0:                       # corner case 1
            corner1()
        elif r == rows - 1 and c == 2 and rows % 8 == 0 and cols == 8:
            corner3()                                       # corner case 3
        elif r == rows - 3 and c == 0 and rows % 8 == 0 and cols == 8:
            corner4()                                       # corner case 4
        elif r == 0 and c == cols - 4:                      # corner case 2
            corner2()
        else:
            utah(r, c)

    def undamaged(r, c):
        return not (grid[row_sub(r + 2)][col_sub(c - 1)]
                    or grid[row_sub(r + 2)][c]
                    or grid[row_sub(r + 2)][col_sub(c + 1)]
                    or grid[r][col_sub(c - 1)])

    # --- main sweep over the interior triangular region -----------------
    row, col = 4, 0
    while row < rows and col < cols:
        if undamaged(row, col):
            r, c = row, col
            i = 0
            while r >= 0 and c < cols and not grid[r][c]:
                place(r, c)
                i += 1
                r -= 1
                c += 2
                r, c = row_sub(rows - i), col_sub(2 * i)
        row, col = row + 2, col + 2

    # --- bottom-left triangle --------------------------------------------
    row, col = rows - 1, 1
    while col < cols and not grid[rows - 1][col]:
        if undamaged(row, col):
            r, c = row, col
            i = 0
            while r < rows and c < cols and not grid[r][c]:
                place(r, c)
                i += 1
                r += 1
                c += 2
                r, c = row_sub((rows - 1 + i) % rows), col_sub(2 * i)
        row, col = row - 2, col + 2

    assert len(order) == rows * cols, \
        f"mapping produced {len(order)} of {rows * cols} positions"
    return order


def _dm_pad_word(n: int) -> int:
    """Standard pad codeword for position ``n`` (0-based) — §5.2.4."""
    if n == 0:
        return 129
    return ((129 + ((((n + 1) * 254) % 253) + 1)) % 254) + 1


def _interleave(data: bytes, ncw: int, ecc_count: int,
                num_blocks: int) -> list[int]:
    """Build the final codeword sequence for multi-block symbols.

    ISO/IEC 16022 §5.9: the data is split into ``num_blocks`` blocks;
    each block holds ``k_hi = ncw // num_blocks`` data codewords, and if
    there is a remainder ``r = ncw % num_blocks`` then *block r* (0-based
    — not the last one!) holds one fewer word (e.g. 64x64: 125 cw per
    block, 88 ECC in 16 blocks of 22 ECC words, so block 7 carries only
    36 data words).  The encoder interleaves by codeword index across
    blocks: d[0][0], d[1][0], …, skipping short positions; likewise for
    the ECC codewords.

    ``data`` may be shorter than the block size allows when an EDIFACT /
    C40 / base-256 segment was terminated with an unpad "latch" codeword
    (§5.4.4); those trailing slots are filled with pad codewords first.
    """
    n = len(data)
    k_hi = ncw // num_blocks            # data cw in most blocks
    r = ncw % num_blocks                # short block index (or none)
    if k_hi == 0:
        raise ValueError("invalid block split")
    if n < ncw:                         # complete to capacity with pads
        data = data + bytes(_dm_pad_word(i) for i in range(n, ncw))
        n = ncw

    blocks_data: list[list[int]] = []
    pos = 0
    for b in range(num_blocks):
        size = k_hi - (1 if b == r else 0)
        blocks_data.append(list(data[pos:pos + size]))
        pos += size
    assert pos == n

    ecc_per_block = [ecc_count // num_blocks] * num_blocks
    for b in range(ecc_count % num_blocks):
        ecc_per_block[b] += 1
    blocks_ecc = [_rs_encode(bytes(blk), e)
                  for blk, e in zip(blocks_data, ecc_per_block)]

    out: list[int] = []
    for i in range(k_hi):               # longest data block length
        for b in range(num_blocks):
            if i < len(blocks_data[b]):
                out.append(blocks_data[b][i])
    max_e = max(ecc_per_block)
    for i in range(max_e):
        for b in range(num_blocks):
            if i < len(blocks_ecc[b]):
                out.append(blocks_ecc[b][i])
    return out


def encode_datamatrix(text: str) -> Image.Image:
    """Encode ASCII text into a 1-bit Data Matrix ECC200 symbol image."""
    words = _dm_ascii_codewords(text)
    chosen = None
    for name in _DM_ORDER:
        if len(words) <= _DM_GEOM[name][4]:      # data codeword capacity
            chosen = name
            break
    if chosen is None:
        raise ValueError("payload too large for supported DM sizes")
    total, ecc, mrows, mcols, ncw, nb = _DM_GEOM[chosen]

    # Pad with the standard pseudo-random sequence (254 / 129 style).
    while len(words) < ncw:
        words.append(_dm_pad_word(len(words)))
    data_bytes = bytes(words[:ncw])
    codewords = _interleave(data_bytes, ncw, ecc, nb)
    assert len(codewords) == total

    bits = iter([((w >> b) & 1) != 0 for w in codewords for b in
                 range(7, -1, -1)])
    grid = [[False] * mcols for _ in range(mrows)]
    positions = _dm_module_positions(mrows, mcols)
    for (r, c), b in zip(positions, bits):
        grid[r][c] = b
    # Any leftover positions (larger mapping than codeword bits require)
    # get the pseudo-random fill pattern.
    filled = set(positions[:len(codewords) * 8])
    for r in range(mrows):
        for c in range(mcols):
            if (r, c) not in filled:
                grid[r][c] = _dm_random_bit(r, c, mrows, mcols)

    # Block layout comes from the size table itself (ISO/IEC 16022
    # Table 1): 1x1 up to 26x26, then 2x2, 4x4, 6x6 and 8x8 blocks.
    nrb = int(nb ** 0.5)
    ncb = nrb
    assert nrb * ncb == nb, f"{chosen}: non-square block layout"
    height = nrb * mrows + 2 * nrb
    width = ncb * mcols + 2 * ncb
    symbol = [[False] * width for _ in range(height)]

    # Clock patterns: bottom row solid, left column solid, top row and
    # right column alternating — repeated for every row/column block.
    for blk_r in range(nrb):
        top = blk_r * (mrows + 2)
        bottom = top + mrows + 1
        for c in range(width):
            symbol[top][c] = (c % 2) == 0          # alternating top
            symbol[bottom][c] = True               # solid bottom
    for blk_c in range(ncb):
        left = blk_c * (mcols + 2)
        right = left + mcols + 1
        for r in range(height):
            symbol[r][left] = True                 # solid left
            symbol[r][right] = (r % 2) == 0        # alternating right

    # Place the data blocks inside their clock frames.
    bh, bw = mrows // nrb, mcols // ncb
    for br in range(nrb):
        for bc in range(ncb):
            base_r = br * (mrows + 2) + 1
            base_c = bc * (mcols + 2) + 1
            for r in range(bh):
                for c in range(bw):
                    symbol[base_r + r][base_c + c] = \
                        grid[br * bh + r][bc * bw + c]

    img = Image.new("1", (width + 4, height + 4), 1)   # white quiet zone
    px = img.load()
    for r in range(height):
        for c in range(width):
            if symbol[r][c]:
                px[c + 2, r + 2] = 0
    return img


