class _GF256:
    """Galois field GF(256) arithmetic for DM Reed-Solomon codewords."""

    def __init__(self, primitive_poly: int = 0x12D):
        self.exp = [0] * 512
        self.log = [0] * 256
        x = 1
        for i in range(255):
            self.exp[i] = x
            self.log[x] = i
            x <<= 1
            if x & 0x100:
                x ^= primitive_poly
        assert x == 1, "primitive polynomial must generate GF(256)"
        for i in range(255, 512):
            self.exp[i] = self.exp[i - 255]

    def mul(self, a: int, b: int) -> int:
        if a == 0 or b == 0:
            return 0
        return self.exp[self.log[a] + self.log[b]]


_GF = _GF256()


def _rs_generator_poly(degree: int) -> list[int]:
    """Reed-Solomon generator polynomial over GF(256), highest power first."""
    g = [1]
    for i in range(degree):
        g.append(0)
        for j in range(len(g) - 1):
            g[j] = _GF.mul(g[j], _GF.exp[i]) ^ g[j + 1]
        del g[-1]
    return g


def _rs_encode(data: bytes, cw_count: int) -> list[int]:
    """Compute ``cw_count`` Reed-Solomon error-correction codewords.

    The generator polynomial has degree ``cw_count`` (``cw_count + 1``
    coefficients); the remainder of the synthetic division is returned.
    """
    gen = _rs_generator_poly(cw_count)
    result = list(data) + [0] * cw_count
    for i in range(len(data)):
        coeff = result[i]
        if coeff:
            for j in range(len(gen)):
                result[i + j] = _GF.mul(gen[j], coeff) ^ result[i + j + 1]
    return result[len(data):]


